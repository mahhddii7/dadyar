import "server-only";

function normalize(question: string) {
  return question.normalize("NFKC").replace(/[يى]/g, "ی").replace(/ك/g, "ک")
    .replace(/[\u200c\u0640]/g, " ").replace(/[؟?!.،]/g, " ").replace(/\s+/g, " ").trim().toLowerCase();
}

export function assistantInfo(question: string): string | null {
  const q = normalize(question);
  if (!/^(?:(?:تو|شما|خودت)\s+)?(?:کی|چه کسی)\s+هستی$|^(?:اسم|نام)\s+(?:تو|شما|خودت)\s+چیست$|^(?:خودت\s+را\s+معرفی\s+کن|خودتو\s+معرفی\s+کن)$|^(?:تو\s+)?چه\s+کار(?:ی)?\s+(?:می\s*کنی|میکنی)$|^داده\s*یار\s+چیست$/u.test(q)) return null;
  return "من داده‌یارم؛ دستیار تحلیل فایل‌هایی که در این برنامه انتخاب می‌کنید. می‌توانم داده‌های جدولی را محاسبه و مقایسه کنم و با کمک مدل زبانی به پرسش‌های تحلیلی دربارهٔ جدول‌ها و اسناد پاسخ بدهم. برای نتیجهٔ قابل اتکا، منبع و محدودیت داده را در پاسخ مشخص می‌کنم. اگر داده کافی نباشد، باید همان را بگویم. این برنامه یک عامل خودمختار برای انجام کارهای بیرون از گفت‌وگو نیست.";
}
